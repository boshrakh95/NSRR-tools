def main():
    parser = argparse.ArgumentParser(
        description="Assemble composite paper figures.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--fig",
                        choices=list(BUILDERS) + ["all"],
                        default="all",
                        help="Figure to build (default: all).")
    parser.add_argument("--figures-dir", required=True,
                        help="Path to phase0_v3 figures dir "
                             "(e.g. results/figures/phase0_v3).")
    parser.add_argument("--out-dir", default="results/figures/assembled",
                        help="Output directory (default: results/figures/assembled).")
    args = parser.parse_args()

    fdir    = Path(args.figures_dir)
    out_dir = Path(args.out_dir)

    if not fdir.exists():
        print(f"ERROR: --figures-dir does not exist: {fdir}", file=sys.stderr)
        sys.exit(1)

    targets = list(BUILDERS) if args.fig == "all" else [args.fig]
    for fid in targets:
        try:
            BUILDERS[fid](fdir, out_dir)
        except Exception as exc:
            print(f"  [ERROR] {fid}: {exc}", file=sys.stderr)
            import traceback; traceback.print_exc(file=sys.stderr)

    print(f"\nDone. Output: {out_dir}")


if __name__ == "__main__":
    main()
