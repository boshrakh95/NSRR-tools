# ── S-Fig 1 — K-Aggregation (test_window_sweep) ────────────────────────────────

def _sweep_path(fdir: Path, task: str, head: str) -> Path:
    """Return the test_window_sweep_auroc.png path, checking the style1 archive
    first (local), then the current figures dir (cluster after regeneration),
    then metric_vs_k_auroc.png as a last fallback.

    Archive layout: results/figures_style1_archive_20260701/phase0_v3/{task}_{head}/
    Current layout: results/figures/phase0_v3/{task}_{head}/
    """
    fname = f"{task}_{head}_test_window_sweep_auroc.png"
    # 1. Archive: sibling of the "figures" parent dir
    archive = fdir.parent.parent / "figures_style1_archive_20260701" / fdir.name
    p_archive = archive / f"{task}_{head}" / fname
    if p_archive.exists():
        return p_archive
    # 2. Current figures dir (regenerated with TBME style on cluster)
    p_current = fdir / f"{task}_{head}" / fname
    if p_current.exists():
        return p_current
    # 3. Fallback: metric_vs_k from iso-compute (same content, mean_prob only)
    return fdir / f"{task}_{head}" / "auroc_test" / "metric_vs_k_auroc.png"


