# ── Image helpers ──────────────────────────────────────────────────────────────

def load_img(path: Path):
    """Load PNG; return None with a warning if missing."""
    if not path.exists():
        print(f"  [WARN] missing: {path}", file=sys.stderr)
        return None
    return mpimg.imread(str(path))


def img_aspect(path: Path) -> float:
    """Return width/height pixel ratio of a PNG, or 1.5 if unreadable."""
    if not path.exists():
        return 1.5
    try:
        img = mpimg.imread(str(path))
        h, w = img.shape[:2]
        return w / h
    except Exception:
        return 1.5


def show_img(ax, img, label=None):
    """Show image in axis preserving its natural aspect ratio.
    Label is drawn inside upper-left with a white backing box.
    """
    if img is None:
        ax.set_facecolor("#ebebeb")
        ax.text(0.5, 0.5, "MISSING", ha="center", va="center",
                transform=ax.transAxes, color="#cc0000", fontsize=7,
                fontfamily=LABEL_FONT)
        ax.set_xticks([]); ax.set_yticks([])
    else:
        # aspect='equal' (imshow default) preserves image proportions — no squishing.
        ax.imshow(img, interpolation="lanczos")
        ax.axis("off")

    if label:
        ax.text(LABEL_X, LABEL_Y, label,
                ha="center", va="top", transform=ax.transAxes,
                fontsize=LABEL_SIZE, fontfamily=LABEL_FONT,
                clip_on=False)   # prevent axes boundary from clipping outside-axis text


# ── Grid builders ──────────────────────────────────────────────────────────────

def make_grid(n_panels: int, n_cols: int, figsize: tuple) -> tuple:
    """
    Standard uniform grid. Excess cells at the end are hidden.
    Returns (fig, axes_flat) where len == n_panels.
    Spacing is set via subplots_adjust — NOT tight_layout, which incorrectly
    inflates inter-row gaps when axes have below-axis text labels.
    """
    n_rows = (n_panels + n_cols - 1) // n_cols
    fig, axes = plt.subplots(n_rows, n_cols, figsize=figsize)
    flat = np.array(axes).ravel() if n_rows * n_cols > 1 else [axes]
    for ax in flat[n_panels:]:
        ax.set_visible(False)
    fig.subplots_adjust(hspace=HSPACE, wspace=WSPACE)
    return fig, flat[:n_panels]


def make_grid_centered(n_panels: int, n_cols: int, figsize: tuple) -> tuple:
    """
    Like make_grid but the last (incomplete) row is horizontally centred.
    Uses a 2×n_cols virtual GridSpec so the offset is exact.
    """
    n_last = n_panels % n_cols
    if n_last == 0:
        return make_grid(n_panels, n_cols, figsize)

    n_rows = (n_panels + n_cols - 1) // n_cols
    vcols  = n_cols * 2          # virtual columns for half-column centering

    fig = plt.figure(figsize=figsize)
    gs  = gridspec.GridSpec(n_rows, vcols, figure=fig,
                             hspace=HSPACE, wspace=WSPACE)

    axes_flat = []
    for row in range(n_rows - 1):
        for col in range(n_cols):
            axes_flat.append(fig.add_subplot(gs[row, col * 2 : col * 2 + 2]))

    # Centre n_last panels in the last row
    offset = n_cols - n_last
    for col in range(n_last):
        start = offset + col * 2
        axes_flat.append(fig.add_subplot(gs[n_rows - 1, start : start + 2]))

    return fig, axes_flat


def save_fig(fig, out_dir: Path, stem: str):
    """Save as PDF and PNG. bbox_inches='tight' trims outer whitespace."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "png"):
        p = out_dir / f"{stem}.{ext}"
        fig.savefig(str(p), dpi=DPI, bbox_inches="tight")
        print(f"  saved → {p}")
    plt.close(fig)


# ── Figsize helpers ─────────────────────────────────────────────────────────────

def fs(n_rows: int, sample_path: Path = None,
       n_cols: int = 3, width: float = FULL_WIDTH,
       row_h: float = None) -> tuple:
    """
    Compute figsize = (width, n_rows * row_h).

    row_h is derived from the source image's aspect ratio when sample_path
    is given — this ensures no squishing.  If sample_path is missing or
    row_h is given explicitly, that value is used directly.

    col_width = width / n_cols
    row_h     = col_width / (img_w / img_h)      # natural height for that width
    """
    if row_h is None:
        aspect = img_aspect(sample_path) if sample_path else 1.5
        col_w  = width / n_cols
        row_h  = col_w / aspect
        # floor: 0.8 in minimum so panels are never invisible; aspect ratio drives height
        row_h  = max(row_h, 0.8)
    return (width, n_rows * row_h)


